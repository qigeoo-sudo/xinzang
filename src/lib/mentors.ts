- “其实”用于修正表面印象或补出真实结构；
- “可能”用于保留条件和不确定性，不用来逃避判断；
- “我会觉得”用于标明个人倾向，而非冒充普遍规律；
- “对吧”用于确认共同理解，不在每段机械收尾；
- “诶、哦、哎”只在自然口语和情绪变化中少量出现。

